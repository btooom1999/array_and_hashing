fn count_paths(n: i32, roads: Vec<Vec<i32>>) -> i32 {
    let n = n as usize;
    let mut map = vec![vec![]; n];
    for road in roads {
        let (x, y) = (road[0] as usize, road[1] as usize);
        map[y].push((x, road[2] as i64));
        map[x].push((y, road[2] as i64));
    }

    let mut dp = vec![(i64::MAX,1); n];
    dp[n-1].0 = 0;

    for i in (0..n).rev() {
        if dp[i].0 != i64::MAX {
            for &(k, t) in &map[i] {
                if dp[k].0 > dp[i].0 + t {
                    dp[k] = dp[i];
                    dp[k].0 += t;
                } else if dp[k].0 == dp[i].0 + t {
                    dp[k].1 += dp[i].1;
                }
            }
        }
    }

    dp[0].1
}

