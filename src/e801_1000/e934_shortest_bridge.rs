use std::collections::{HashSet, VecDeque};

const DIRECTIONS: [(i32, i32); 4] = [(0,1), (0,-1), (1,0), (-1,0)];

fn find_all_first_island(
    i: i32,
    j: i32,
    n: i32,
    visited: &mut HashSet<(i32, i32)>,
    grid: &Vec<Vec<i32>>,
    island: &mut HashSet<(i32, i32)>
) {
    if visited.contains(&(i, j)) {
        return;
    }

    visited.insert((i, j));
    for direct in DIRECTIONS {
        let ni = direct.0 + i;
        let nj = direct.1 + j;

        if ni < 0 || nj < 0 || ni == n || nj == n {
            continue;
        }

        if grid[ni as usize][nj as usize] == 0 {
            island.insert((i, j));
            continue;
        }

        find_all_first_island(ni, nj, n, visited, grid, island);
    }
}

fn shortest_bridge(mut grid: Vec<Vec<i32>>) -> i32 {
    let n = grid.len();
    let mut i = 0;
    let mut j = 0;
    while grid[i][j] == 0 {
        j += 1;
        j %= n;

        if j == 0 {
            i += 1;
        }
    }

    let mut first_island = HashSet::new();
    let mut visited= HashSet::new();
    find_all_first_island(i as i32, j as i32, n as i32, &mut visited, &grid, &mut first_island);

    let n = n as i32;
    let mut queue = first_island.into_iter().map(|v| (v.0, v.1, 0)).collect::<VecDeque<_>>();
    while let Some((i, j, dist)) = queue.pop_front() {
        for direct in DIRECTIONS {
            let i = direct.0 + i;
            let j = direct.1 + j;

            if i < 0 || j < 0 || i == n || j == n {
                continue;
            }

            if grid[i as usize][j as usize] == 1 {
                if !visited.contains(&(i, j)) {
                    return dist;
                }

                continue;
            }

            grid[i as usize][j as usize] = 1;
            visited.insert((i, j));
            queue.push_back((i, j, dist+1));
        }
    }

    -1
}

